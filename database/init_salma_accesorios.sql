CREATE TABLE cities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    CONSTRAINT uk_city_name UNIQUE (name),
    CONSTRAINT chk_cities_name CHECK (length(trim(name)) >= 2)
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    slug VARCHAR(100) NOT NULL,
    CONSTRAINT uk_categories_name UNIQUE (name),
    CONSTRAINT uk_categories_slug UNIQUE (slug),
    CONSTRAINT chk_categories_name CHECK (length(trim(name)) >= 3),
    CONSTRAINT chk_categories_slug CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(60) NOT NULL,
    second_name VARCHAR(60),
    first_last_name VARCHAR(60) NOT NULL,
    second_last_name VARCHAR(60) NOT NULL,
    email VARCHAR(120) NOT NULL,
    username VARCHAR(40) NOT NULL,
    phone VARCHAR(10) NOT NULL,
    password VARCHAR(255) NOT NULL,
    city_id BIGINT NOT NULL,
    address VARCHAR(160) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'CLIENTE',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_phone UNIQUE (phone),
    CONSTRAINT fk_users_city FOREIGN KEY (city_id) REFERENCES cities (id),
    CONSTRAINT chk_users_role CHECK (role IN ('ADMIN', 'CLIENTE')),
    CONSTRAINT chk_users_phone CHECK (phone ~ '^3[0-9]{9}$')
);

