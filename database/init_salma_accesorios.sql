CREATE OR REPLACE FUNCTION create_cart_for_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO carts (user_id) VALUES (NEW.id)
    ON CONFLICT (user_id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_create_cart_for_new_user
AFTER INSERT ON users
FOR EACH ROW
EXECUTE FUNCTION create_cart_for_new_user();

CREATE OR REPLACE FUNCTION refresh_product_average_rating()
RETURNS TRIGGER AS $$
DECLARE
    affected_product_id BIGINT;
BEGIN
    affected_product_id := COALESCE(NEW.product_id, OLD.product_id);

    UPDATE products
    SET average_rating = COALESCE((
        SELECT ROUND(AVG(rating)::numeric, 2)
        FROM reviews
        WHERE product_id = affected_product_id
          AND approved = TRUE
    ), 0)
    WHERE id = affected_product_id;

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reviews_refresh_product_rating
AFTER INSERT OR UPDATE OR DELETE ON reviews
FOR EACH ROW
EXECUTE FUNCTION refresh_product_average_rating();

