CREATE OR REPLACE FUNCTION refresh_product_average_rating()
RETURNS TRIGGER AS $$
DECLARE
    affected_product_id BIGINT;
BEGIN
    affected_product_id := COALESCE(NEW.product_id, OLD.product_id);

    UPDATE products
    SET average_rating = COALESCE((
        SELECT ROUND(AVG(rating)::numeric, 2)
        FROM reviews
        WHERE product_id = affected_product_id
          AND approved = TRUE
    ), 0)
    WHERE id = affected_product_id;

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reviews_refresh_rating
AFTER INSERT OR UPDATE OR DELETE ON reviews
FOR EACH ROW
EXECUTE FUNCTION refresh_product_average_rating();

